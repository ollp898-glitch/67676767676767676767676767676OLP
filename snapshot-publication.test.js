const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {prepareSnapshot,readPreparedFile,MAX_FILE_BYTES,PART_BYTES}=require('./snapshot-publication');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'betx-publication-test-'));
try{
  assert.equal(MAX_FILE_BYTES,100*1024*1024);
  assert.equal(PART_BYTES,80*1024*1024);
  const source=path.join(root,'source'),destination=path.join(root,'destination');
  fs.mkdirSync(source);
  fs.writeFileSync(path.join(source,'markets.jsonl'),'{"outcome_id":"a"}\n'.repeat(20));
  fs.writeFileSync(path.join(source,'excluded.jsonl'),'{"reason":"no_ask"}\n');
  fs.writeFileSync(path.join(source,'unrecognized.jsonl'),'{"market_id":"abc","reason":"unclassified_market_type"}\n');
  fs.writeFileSync(path.join(source,'exclusion-summary.json'),'{"counts":{"unrecognized_markets":1}}\n');
  fs.writeFileSync(path.join(source,'exclusion-history.jsonl'),'{"snapshot_at":"2026-10-18T00:00:00Z"}\n');
  fs.writeFileSync(path.join(source,'index.json'),JSON.stringify({scan_status:'complete',pagination_complete:true}));
  fs.writeFileSync(path.join(source,'wide-combo-error.json'),'obsolete marker');
  const manifest=prepareSnapshot(source,destination,{maxFileBytes:100,partBytes:60});
  assert.deepEqual(Object.keys(manifest.files).sort(),['excluded.jsonl','exclusion-history.jsonl','exclusion-summary.json','index.json','markets.jsonl','unrecognized.jsonl']);
  assert(!fs.existsSync(path.join(destination,'wide-combo-error.json')));
  assert(manifest.split_files['markets.jsonl'].parts.length>1);
  assert.deepEqual(readPreparedFile(destination,'markets.jsonl'),fs.readFileSync(path.join(source,'markets.jsonl')));
  assert.deepEqual(readPreparedFile(destination,'unrecognized.jsonl'),fs.readFileSync(path.join(source,'unrecognized.jsonl')));
  assert.deepEqual(readPreparedFile(destination,'exclusion-summary.json'),fs.readFileSync(path.join(source,'exclusion-summary.json')));
  for(const part of manifest.split_files['markets.jsonl'].parts)assert(part.bytes<=60);
  const previous=fs.readFileSync(path.join(destination,'publication-manifest.json'));
  fs.writeFileSync(path.join(source,'index.json'),JSON.stringify({scan_status:'incomplete',pagination_complete:false}));
  assert.throws(()=>prepareSnapshot(source,destination),/Scanner incomplete/);
  assert.deepEqual(fs.readFileSync(path.join(destination,'publication-manifest.json')),previous);
  console.log('Publication tests passed: three files, verified splitting and previous snapshot retention.');
}finally{fs.rmSync(root,{recursive:true,force:true});}
